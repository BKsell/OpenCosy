const E68H3P_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E68H3PLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E68H3PIn (list, v) {
  for (const x of list) { if (E68H3PLower(x) === v) return true }
  return false
}

function E68H3PClassify (tok) {
  const v = E68H3PLower(String(tok == null ? '' : tok).trim())
  if (E68H3PIn(E68H3P_BLOCK, v)) return E68H3P_CLASS.BLOCK
  if (E68H3PIn(E68H3P_WARN, v)) return E68H3P_CLASS.WARN
  if (E68H3PIn(E68H3P_ALLOW, v)) return E68H3P_CLASS.ALLOW
  return E68H3P_CLASS.UNKNOWN
}

