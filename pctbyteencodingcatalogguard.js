const PB2_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function PB2Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function PB2In (list, v) {
  for (const x of list) { if (PB2Lower(x) === v) return true }
  return false
}

function PB2Classify (tok) {
  const v = PB2Lower(String(tok == null ? '' : tok).trim())
  if (PB2In(PB2_BLOCK, v)) return PB2_CLASS.BLOCK
  if (PB2In(PB2_WARN, v)) return PB2_CLASS.WARN
  if (PB2In(PB2_ALLOW, v)) return PB2_CLASS.ALLOW
  return PB2_CLASS.UNKNOWN
}

