function E70C5LLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70C5LIn (list, v) {
  for (const x of list) { if (E70C5LLower(x) === v) return true }
  return false
}

function E70C5LClassify (tok) {
  const v = E70C5LLower(String(tok == null ? '' : tok))
  if (E70C5LIn(E70C5L_BLOCK, v)) return E70C5L_CLASS.BLOCK
  if (E70C5LIn(E70C5L_WARN, v)) return E70C5L_CLASS.WARN
  if (E70C5LIn(E70C5L_ALLOW, v)) return E70C5L_CLASS.ALLOW
  return E70C5L_CLASS.UNKNOWN
}

