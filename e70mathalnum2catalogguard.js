const E70U11_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70U11Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70U11In (list, v) {
  for (const x of list) { if (E70U11Lower(x) === v) return true }
  return false
}

function E70U11Classify (tok) {
  const v = E70U11Lower(String(tok == null ? '' : tok))
  if (E70U11In(E70U11_BLOCK, v)) return E70U11_CLASS.BLOCK
  if (E70U11In(E70U11_WARN, v)) return E70U11_CLASS.WARN
  if (E70U11In(E70U11_ALLOW, v)) return E70U11_CLASS.ALLOW
  return E70U11_CLASS.UNKNOWN
}

