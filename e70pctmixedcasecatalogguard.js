const E70PMC_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70PMCLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70PMCIn (list, v) {
  for (const x of list) { if (E70PMCLower(x) === v) return true }
  return false
}

function E70PMCClassify (tok) {
  const v = E70PMCLower(String(tok == null ? '' : tok))
  if (E70PMCIn(E70PMC_BLOCK, v)) return E70PMC_CLASS.BLOCK
  if (E70PMCIn(E70PMC_WARN, v)) return E70PMC_CLASS.WARN
  if (E70PMCIn(E70PMC_ALLOW, v)) return E70PMC_CLASS.ALLOW
  return E70PMC_CLASS.UNKNOWN
}

