const HX2_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function HX2Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function HX2In (list, v) {
  for (const x of list) { if (HX2Lower(x) === v) return true }
  return false
}

function HX2Classify (tok) {
  const v = HX2Lower(String(tok == null ? '' : tok).trim())
  if (HX2In(HX2_BLOCK, v)) return HX2_CLASS.BLOCK
  if (HX2In(HX2_WARN, v)) return HX2_CLASS.WARN
  if (HX2In(HX2_ALLOW, v)) return HX2_CLASS.ALLOW
  return HX2_CLASS.UNKNOWN
}

