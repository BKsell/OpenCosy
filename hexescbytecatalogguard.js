const HB2_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function HB2Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function HB2In (list, v) {
  for (const x of list) { if (HB2Lower(x) === v) return true }
  return false
}

function HB2Classify (tok) {
  const v = HB2Lower(String(tok == null ? '' : tok).trim())
  if (HB2In(HB2_BLOCK, v)) return HB2_CLASS.BLOCK
  if (HB2In(HB2_WARN, v)) return HB2_CLASS.WARN
  if (HB2In(HB2_ALLOW, v)) return HB2_CLASS.ALLOW
  return HB2_CLASS.UNKNOWN
}

