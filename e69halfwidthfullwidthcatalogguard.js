const E69T36_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E69T36Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E69T36In (list, v) {
  for (const x of list) { if (E69T36Lower(x) === v) return true }
  return false
}

function E69T36Classify (tok) {
  const v = E69T36Lower(String(tok == null ? '' : tok))
  if (E69T36In(E69T36_BLOCK, v)) return E69T36_CLASS.BLOCK
  if (E69T36In(E69T36_WARN, v)) return E69T36_CLASS.WARN
  if (E69T36In(E69T36_ALLOW, v)) return E69T36_CLASS.ALLOW
  return E69T36_CLASS.UNKNOWN
}

