function CSSLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function CSSIn (list, v) {
  for (const x of list) { if (CSSLower(x) === v) return true }
  return false
}

function CSSClassify (tok) {
  const v = CSSLower(String(tok == null ? '' : tok).trim())
  if (CSSIn(CSS_BLOCK, v)) return CSS_CLASS.BLOCK
  if (CSSIn(CSS_WARN, v)) return CSS_CLASS.WARN
  if (CSSIn(CSS_ALLOW, v)) return CSS_CLASS.ALLOW
  return CSS_CLASS.UNKNOWN
}

