const OB2_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function OB2Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function OB2In (list, v) {
  for (const x of list) { if (OB2Lower(x) === v) return true }
  return false
}

function OB2Classify (tok) {
  const v = OB2Lower(String(tok == null ? '' : tok).trim())
  if (OB2In(OB2_BLOCK, v)) return OB2_CLASS.BLOCK
  if (OB2In(OB2_WARN, v)) return OB2_CLASS.WARN
  if (OB2In(OB2_ALLOW, v)) return OB2_CLASS.ALLOW
  return OB2_CLASS.UNKNOWN
}

