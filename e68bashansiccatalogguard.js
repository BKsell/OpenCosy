const E68BSH_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E68BSHLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E68BSHIn (list, v) {
  for (const x of list) { if (E68BSHLower(x) === v) return true }
  return false
}

function E68BSHClassify (tok) {
  const v = E68BSHLower(String(tok == null ? '' : tok).trim())
  if (E68BSHIn(E68BSH_BLOCK, v)) return E68BSH_CLASS.BLOCK
  if (E68BSHIn(E68BSH_WARN, v)) return E68BSH_CLASS.WARN
  if (E68BSHIn(E68BSH_ALLOW, v)) return E68BSH_CLASS.ALLOW
  return E68BSH_CLASS.UNKNOWN
}

