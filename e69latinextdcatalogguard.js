const E69T32_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E69T32Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E69T32In (list, v) {
  for (const x of list) { if (E69T32Lower(x) === v) return true }
  return false
}

function E69T32Classify (tok) {
  const v = E69T32Lower(String(tok == null ? '' : tok))
  if (E69T32In(E69T32_BLOCK, v)) return E69T32_CLASS.BLOCK
  if (E69T32In(E69T32_WARN, v)) return E69T32_CLASS.WARN
  if (E69T32In(E69T32_ALLOW, v)) return E69T32_CLASS.ALLOW
  return E69T32_CLASS.UNKNOWN
}

