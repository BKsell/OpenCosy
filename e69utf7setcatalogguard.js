const E69U7S_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E69U7SLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E69U7SIn (list, v) {
  for (const x of list) { if (E69U7SLower(x) === v) return true }
  return false
}

function E69U7SClassify (tok) {
  const v = E69U7SLower(String(tok == null ? '' : tok))
  if (E69U7SIn(E69U7S_BLOCK, v)) return E69U7S_CLASS.BLOCK
  if (E69U7SIn(E69U7S_WARN, v)) return E69U7S_CLASS.WARN
  if (E69U7SIn(E69U7S_ALLOW, v)) return E69U7S_CLASS.ALLOW
  return E69U7S_CLASS.UNKNOWN
}

