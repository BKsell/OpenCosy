const E70QPL_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70QPLLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70QPLIn (list, v) {
  for (const x of list) { if (E70QPLLower(x) === v) return true }
  return false
}

function E70QPLClassify (tok) {
  const v = E70QPLLower(String(tok == null ? '' : tok))
  if (E70QPLIn(E70QPL_BLOCK, v)) return E70QPL_CLASS.BLOCK
  if (E70QPLIn(E70QPL_WARN, v)) return E70QPL_CLASS.WARN
  if (E70QPLIn(E70QPL_ALLOW, v)) return E70QPL_CLASS.ALLOW
  return E70QPL_CLASS.UNKNOWN
}

