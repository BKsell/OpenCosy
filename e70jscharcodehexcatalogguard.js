const E70JCH_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70JCHLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70JCHIn (list, v) {
  for (const x of list) { if (E70JCHLower(x) === v) return true }
  return false
}

function E70JCHClassify (tok) {
  const v = E70JCHLower(String(tok == null ? '' : tok))
  if (E70JCHIn(E70JCH_BLOCK, v)) return E70JCH_CLASS.BLOCK
  if (E70JCHIn(E70JCH_WARN, v)) return E70JCH_CLASS.WARN
  if (E70JCHIn(E70JCH_ALLOW, v)) return E70JCH_CLASS.ALLOW
  return E70JCH_CLASS.UNKNOWN
}

