function HADLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function HADIn (list, v) {
  for (const x of list) { if (HADLower(x) === v) return true }
  return false
}

function HADClassify (tok) {
  const v = HADLower(String(tok == null ? '' : tok).trim())
  if (HADIn(HAD_BLOCK, v)) return HAD_CLASS.BLOCK
  if (HADIn(HAD_WARN, v)) return HAD_CLASS.WARN
  if (HADIn(HAD_ALLOW, v)) return HAD_CLASS.ALLOW
  return HAD_CLASS.UNKNOWN
}

