function WADLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function WADIn (list, v) {
  for (const x of list) { if (WADLower(x) === v) return true }
  return false
}

function WADClassify (tok) {
  const v = WADLower(String(tok == null ? '' : tok).trim())
  if (WADIn(WAD_BLOCK, v)) return WAD_CLASS.BLOCK
  if (WADIn(WAD_WARN, v)) return WAD_CLASS.WARN
  if (WADIn(WAD_ALLOW, v)) return WAD_CLASS.ALLOW
  return WAD_CLASS.UNKNOWN
}

