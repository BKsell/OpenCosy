const E70CES_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70CESLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70CESIn (list, v) {
  for (const x of list) { if (E70CESLower(x) === v) return true }
  return false
}

function E70CESClassify (tok) {
  const v = E70CESLower(String(tok == null ? '' : tok))
  if (E70CESIn(E70CES_BLOCK, v)) return E70CES_CLASS.BLOCK
  if (E70CESIn(E70CES_WARN, v)) return E70CES_CLASS.WARN
  if (E70CESIn(E70CES_ALLOW, v)) return E70CES_CLASS.ALLOW
  return E70CES_CLASS.UNKNOWN
}

