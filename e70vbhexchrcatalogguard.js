const E70VHC_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70VHCLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70VHCIn (list, v) {
  for (const x of list) { if (E70VHCLower(x) === v) return true }
  return false
}

function E70VHCClassify (tok) {
  const v = E70VHCLower(String(tok == null ? '' : tok))
  if (E70VHCIn(E70VHC_BLOCK, v)) return E70VHC_CLASS.BLOCK
  if (E70VHCIn(E70VHC_WARN, v)) return E70VHC_CLASS.WARN
  if (E70VHCIn(E70VHC_ALLOW, v)) return E70VHC_CLASS.ALLOW
  return E70VHC_CLASS.UNKNOWN
}

