const E70C1L_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E70C1LLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E70C1LIn (list, v) {
  for (const x of list) { if (E70C1LLower(x) === v) return true }
  return false
}

function E70C1LClassify (tok) {
  const v = E70C1LLower(String(tok == null ? '' : tok))
  if (E70C1LIn(E70C1L_BLOCK, v)) return E70C1L_CLASS.BLOCK
  if (E70C1LIn(E70C1L_WARN, v)) return E70C1L_CLASS.WARN
  if (E70C1LIn(E70C1L_ALLOW, v)) return E70C1L_CLASS.ALLOW
  return E70C1L_CLASS.UNKNOWN
}

