function DENLower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function DENIn (list, v) {
  for (const x of list) { if (DENLower(x) === v) return true }
  return false
}

function DENClassify (tok) {
  const v = DENLower(String(tok == null ? '' : tok).trim())
  if (DENIn(DEN_BLOCK, v)) return DEN_CLASS.BLOCK
  if (DENIn(DEN_WARN, v)) return DEN_CLASS.WARN
  if (DENIn(DEN_ALLOW, v)) return DEN_CLASS.ALLOW
  return DEN_CLASS.UNKNOWN
}

