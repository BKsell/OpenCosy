const E68O03_ALLOW = Object.freeze([
  'ascii-only',
  'nfkc-normalized',
  'punycode-label',
])

function E68O03Lower (x) {
  let out = ''
  for (let i = 0; i < x.length; i++) {
    const c = x.charCodeAt(i)
    out += c >= 65 && c <= 90 ? String.fromCharCode(c + 32) : x[i]
  }
  return out
}

function E68O03In (list, v) {
  for (const x of list) { if (E68O03Lower(x) === v) return true }
  return false
}

function E68O03Classify (tok) {
  const v = E68O03Lower(String(tok == null ? '' : tok).trim())
  if (E68O03In(E68O03_BLOCK, v)) return E68O03_CLASS.BLOCK
  if (E68O03In(E68O03_WARN, v)) return E68O03_CLASS.WARN
  if (E68O03In(E68O03_ALLOW, v)) return E68O03_CLASS.ALLOW
  return E68O03_CLASS.UNKNOWN
}

